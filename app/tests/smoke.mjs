import { chromium } from "@playwright/test";

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
page.on("pageerror", (error) => errors.push(error.message));
await page.addInitScript(() => localStorage.clear());

await page.goto("http://127.0.0.1:4173", { waitUntil: "networkidle" });
await page.waitForFunction(() => document.querySelector("#provenance")?.textContent.includes("male-cns:v1.0"));
await page.locator("#quickSkillBar").waitFor({ state: "visible" });
const webglCanvas = page.locator('[data-testid="arena-webgl"]');
await webglCanvas.waitFor({ state: "visible" });
const webglSize = await webglCanvas.evaluate((canvas) => ({ width: canvas.width, height: canvas.height }));
const enemySummary = await page.locator("#enemySummary").textContent();
await page.click('[data-scenario="ruins"]');
const ruinsDescription = await page.locator("#scenarioDescription").textContent();
await page.click('[data-scenario="garden"]');
await page.click('[data-flight="takeoff"]');
await page.waitForTimeout(850);
const flightAltitude = Number((await page.locator("#altitudeValue").textContent()).replace("m", ""));
const flightMotion = await page.locator("#motionValue").textContent();
const flightSpeed = Number((await page.locator("#speedValue").textContent()).replace(/[^\d.]/g, ""));
const arenaNote = await page.locator(".arena-note").textContent();
const pageTitle = await page.title();
await page.click('[data-flight="auto"]');
const affinityBefore = Number(await page.locator("#affinityMeter").getAttribute("value"));
const skillBefore = Number(await page.locator("#skillMeter").getAttribute("value"));
await page.click("#feedOwner");
await page.selectOption("#personalitySelect", "brave");
await page.selectOption("#enemyStrengthSelect", "0.25");
await page.selectOption("#enemyHostilitySelect", "1");
await page.selectOption("#attackRewardSelect", "0.8");
await page.click('[data-command="attack"]');
await page.click("#trainAttack");
await page.click("#trainAttack");
await page.click("#trainAttack");
const affinityAfter = Number(await page.locator("#affinityMeter").getAttribute("value"));
const skillAfter = Number(await page.locator("#skillMeter").getAttribute("value"));
await page.selectOption("#creatureElement", "earth");
await page.locator('[data-use-skill="shell"]').first().click();
await page.waitForTimeout(1300);
const learningLog = await page.locator("#eventLog").textContent();
const shellButtonText = await page.locator('[data-use-skill="shell"]').first().textContent();
await page.click('[data-stimulus="sweet"]');
await page.waitForTimeout(700);
const feedAfterSweet = await page.locator("#feedMeter").getAttribute("value");
await page.click('[data-stimulus="loom-left"]');
await page.waitForTimeout(500);
const escapeAfterLoom = await page.locator("#escapeMeter").getAttribute("value");
await page.selectOption("#duelPlayerElement", "fire");
await page.selectOption("#duelRivalElement", "wood");
await page.selectOption("#duelPursuit", "adaptive");
await page.click("#startDuel");
await page.waitForFunction(() => {
  const log = document.querySelector("#eventLog")?.textContent || "";
  return ["视觉反射将根据实时弹道", "闪过了", "命中", "防御姿态"].some((phrase) => log.includes(phrase));
}, null, { timeout: 12_000 });
const duelPlayerHealth = Number(await page.locator("#duelPlayerHealth").getAttribute("value"));
const duelRivalHealth = Number(await page.locator("#duelRivalHealth").getAttribute("value"));
const duelState = await page.locator("#duelState").textContent();
const duelPlayerTactic = await page.locator("#duelPlayerTactic").textContent();
const duelRivalTactic = await page.locator("#duelRivalTactic").textContent();
const duelVisionReadout = await page.locator("#duelVisionReadout").textContent();
const duelLog = await page.locator("#eventLog").textContent();
await page.click("#combatCameraToggle");
const cameraMode = await page.locator("#combatCameraToggle").textContent();
await page.screenshot({ path: "../artifacts/digital-fly-v2-learning.png", fullPage: true });

if (errors.length) throw new Error(`Browser errors: ${errors.join(" | ")}`);
if (webglSize.width < 500 || webglSize.height < 300) throw new Error(`3D canvas was not sized: ${JSON.stringify(webglSize)}`);
if (!enemySummary.includes("6名敌人") || !enemySummary.includes("2座洞穴")) throw new Error(`Multi-enemy world did not load: ${enemySummary}`);
if (!ruinsDescription.includes("矮墙")) throw new Error(`Ruins scenario did not load: ${ruinsDescription}`);
if (flightAltitude < 45 || !flightMotion.includes("飞")) throw new Error(`Takeoff failed: altitude=${flightAltitude}, motion=${flightMotion}`);
if (flightSpeed < 500) throw new Error(`Flight speed was not visibly faster than walking: ${flightSpeed}`);
if (!arenaNote.includes("7200 × 4800") || !arenaNote.includes("1600") || !arenaNote.includes("真实高度碰撞")) throw new Error(`Expanded terrain explanation missing: ${arenaNote}`);
if (!pageTitle.includes("属性萤翼龙")) throw new Error(`Winged dragon skin title missing: ${pageTitle}`);
if (affinityAfter <= affinityBefore) throw new Error(`Feeding did not increase affinity: ${affinityBefore} -> ${affinityAfter}`);
if (skillAfter <= skillBefore) throw new Error(`Training did not increase skill: ${skillBefore} -> ${skillAfter}`);
if (!learningLog.includes("岩壳防御") || !shellButtonText.includes("s")) throw new Error(`Skill framework was not observed: ${learningLog} / ${shellButtonText}`);
if (Number(feedAfterSweet) <= 0.08) throw new Error(`Sweet stimulus did not raise feed meter: ${feedAfterSweet}`);
if (Number(escapeAfterLoom) <= 0.15) throw new Error(`Loom stimulus did not raise escape meter: ${escapeAfterLoom}`);
if (!Number.isFinite(duelPlayerHealth) || !Number.isFinite(duelRivalHealth)) throw new Error(`Duel health became invalid: player=${duelPlayerHealth}, rival=${duelRivalHealth}, state=${duelState}`);
const validAirTactics = ["搜索最后目击位置", "开局保持警戒并试探", "全图换位寻找奇袭角度", "凭气味拉开视觉外距离", "识别冲锋并自适应反击", "实时维持射程并侧移", "缩短距离寻找进攻窗口", "距离过近，主动脱离", "提前识别边界并沿障碍绕行", "身体反射避免碰撞", "视觉反射快速滑步闪避", "失去战意", "发现逃跑", "放弃追击", "受击失衡"];
if (!validAirTactics.some((label) => duelPlayerTactic.startsWith(label)) || !duelPlayerTactic.includes("m")) throw new Error(`Unknown player air tactic: ${duelPlayerTactic}`);
if (!validAirTactics.some((label) => duelRivalTactic.startsWith(label)) || !duelRivalTactic.includes("m")) throw new Error(`Unknown rival air tactic: ${duelRivalTactic}`);
if (!duelVisionReadout.includes("战斗阶段") || !duelVisionReadout.includes("纯视觉距离") || !duelVisionReadout.includes("气味追踪") || !duelVisionReadout.includes("经验记忆")) throw new Error(`Combat perception explanation missing: ${duelVisionReadout}`);
if (!cameraMode.includes("自由观战")) throw new Error(`Camera toggle did not release spectator view: ${cameraMode}`);
if (!["视觉反射将根据实时弹道", "闪过了", "命中", "防御姿态"].some((phrase) => duelLog.includes(phrase))) throw new Error(`Combat feedback missing from duel log: ${duelLog}`);
console.log(JSON.stringify({ webglSize, flightAltitude, flightMotion, flightSpeed, affinityBefore, affinityAfter, skillBefore, skillAfter, feedAfterSweet: Number(feedAfterSweet), escapeAfterLoom: Number(escapeAfterLoom), duelPlayerHealth, duelRivalHealth, duelState, duelPlayerTactic, duelRivalTactic, errors }));
await browser.close();
